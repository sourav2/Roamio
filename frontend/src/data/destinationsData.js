export function calculateItineraryTotals(destinationsByDay, travellerCount = 1) {
  let totalCost = 0;
  let totalHours = 0;
  const count = Math.max(1, typeof travellerCount === 'number' && !isNaN(travellerCount) ? travellerCount : 1);

  Object.values(destinationsByDay || {}).forEach((dayItems) => {
    (dayItems || []).forEach((item) => {
      const baseCost = parsePlaceCost(item);
      totalCost += baseCost * count;
      totalHours += parsePlaceHours(item);
    });
  });

  return {
    totalCost,
    totalHours,
    cost: totalCost > 0 ? `₹${totalCost.toLocaleString('en-IN')}` : '₹0',
    totalTime: totalHours > 0 ? `${totalHours} H` : '0 H',
  };
}

/**
 * Calculate dynamic budget categories (Transport, Stay, Food, Activities) based on actual itinerary
 */
export function calculateDynamicBudgetCategories(destinationsByDay, travellerCount = 1) {
  const count = Math.max(1, typeof travellerCount === 'number' && !isNaN(travellerCount) ? travellerCount : 1);
  const allAddedItems = Object.values(destinationsByDay || {}).flat();
  const totalItemsCount = allAddedItems.length;

  if (totalItemsCount === 0) {
    return {
      totalAmount: 0,
      totalFormatted: '₹0',
      activeDaysCount: 0,
      categories: [
        { name: 'Transport', amount: 0, percentage: 0, color: '#164A3A' },
        { name: 'Stay', amount: 0, percentage: 0, color: '#46B392' },
        { name: 'Food', amount: 0, percentage: 0, color: '#EBBA58' },
        { name: 'Activities', amount: 0, percentage: 0, color: '#949494' },
      ],
    };
  }

  // Determine active days that have destinations
  const activeDaysCount = Object.keys(destinationsByDay || {}).filter(
    (d) => (destinationsByDay[d] || []).length > 0
  ).length || 1;

  // Activities: Sum of place estimated/actual costs * traveller count
  const activityAmount = allAddedItems.reduce((sum, item) => sum + (parsePlaceCost(item) || 200) * count, 0);

  // Transport: Local transit & transfers based on stops and active days
  const transportAmount = (400 * count * activeDaysCount) + (totalItemsCount * 250);

  // Stay: Homestay/hotel allocation per room per active night
  const stayAmount = Math.ceil(count / 2) * 1800 * activeDaysCount;

  // Food: Meals per traveller across active days
  const foodAmount = 600 * count * activeDaysCount;

  const totalAmount = transportAmount + stayAmount + foodAmount + activityAmount;

  // Compute percentages ensuring exact sum to 100%
  const pTransport = Math.round((transportAmount / totalAmount) * 100);
  const pStay = Math.round((stayAmount / totalAmount) * 100);
  const pFood = Math.round((foodAmount / totalAmount) * 100);
  const pActivities = Math.max(0, 100 - (pTransport + pStay + pFood));

  return {
    totalAmount,
    totalFormatted: `₹ ${totalAmount.toLocaleString('en-IN')}`,
    activeDaysCount,
    categories: [
      { name: 'Transport', amount: transportAmount, percentage: pTransport, color: '#164A3A' },
      { name: 'Stay', amount: stayAmount, percentage: pStay, color: '#46B392' },
      { name: 'Food', amount: foodAmount, percentage: pFood, color: '#EBBA58' },
      { name: 'Activities', amount: activityAmount, percentage: pActivities, color: '#949494' },
    ],
  };
}
